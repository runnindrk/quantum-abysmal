# Render CUDA Provider Macro

def render_cuda_macro(hoppings, num_orbitals):
    lines = []

    lines.append("")
    lines.append("#define CODEGEN_CUDA_PROVIDER_KPM_SPARSE(lattice, a, b, x, y, threadIdx, sFirstReduceData, sSecondReduceData)")

    # Temporary variable
    lines.append("")
    lines.append(f"    double temp[{num_orbitals}] = {{}};")

    lines.append("")

    # Hopping terms
    lines.append("    /* Hopping terms (including Hermitian conjugates) */")
    for hop in hoppings:
        lines.append(
            f'    temp[{hop["orbitalHop"][0]}] += lattice.hoppings[{hop["macro_idx"]}].hoppingStrength * b[ARRAY_IDX(x, y, {hop["latticeHop"][0]}, {hop["latticeHop"][1]}, {hop["orbitalHop"][1]})];'
        )

    lines.append("")

    # Output update
    lines.append("    /* Output update */")
    for i in range(num_orbitals):
        lines.append(
            f'    a[ARRAY_IDX(x, y, 0, 0, {i})] = 2 * temp[{i}] - a[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    lines.append("")

    # First moment
    lines.append("    /* First moment */")
    for i in range(num_orbitals):
        lines.append(
            f'    sFirstReduceData[threadIdx.x] += b[ARRAY_IDX(x, y, 0, 0, {i})] * b[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    lines.append("")

    # Second moment
    lines.append("    /* Second moment */")
    for i in range(num_orbitals):
        lines.append(
            f'    sSecondReduceData[threadIdx.x] += a[ARRAY_IDX(x, y, 0, 0, {i})] * b[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    # Calculate padding
    max_len = max(len(line) for line in lines if line.strip())
    tab_size = 4
    space_count = ((max_len + tab_size) // tab_size) * tab_size
    padded_lines = [(line + " " * (space_count - len(line)) + "\\") for line in lines]

    return "\n".join(padded_lines)

# =================================================================================================
# Render Templates

def render_guarded(header, guard, body):
    return header + GUARD_INIT(guard) + body + GUARD_END(guard)

lattice_template = Template(lattice_template_str)
lattice_rendered = render_guarded(
    COPYRIGHT_HEADER,
    "QUANTUM_ABYSMAL_SRC_CODEGEN_LATTICE_HPP",
    lattice_template.render(
        num_orbitals=len(orbital_map),
        hoppings=all_hoppings
    )
)

macro_cuda_rendered = render_guarded(
    COPYRIGHT_HEADER,
    "QUANTUM_ABYSMAL_SRC_CUDAPROVIDER_CODEGEN_UNROLLEDKPMSPARSE_HPP",
    render_cuda_macro(
        num_orbitals=len(orbital_map),
        hoppings=all_hoppings
    )
)

macro_cpu_rendered = render_guarded(
    COPYRIGHT_HEADER,
    "QUANTUM_ABYSMAL_SRC_CPUPROVIDER_CODEGEN_UNROLLEDKPMSPARSE_HPP",
    render_cpu_macro(
        num_orbitals=len(orbital_map),
        hoppings=all_hoppings
    )
)

# =================================================================================================
# Write Files

with open("src/lattice/codegen/Codegen_LatticeStructure.hpp", "w") as f:
    f.write(lattice_rendered)

with open("src/providers/cuda_provider/kpm/density_of_states/standard/codegen/Codegen_UnrolledKpmSparse.hpp", "w") as f:
    f.write(macro_cuda_rendered)

with open("src/providers/cpu_provider/kpm/density_of_states/standard/codegen/Codegen_UnrolledKpmSparse.hpp", "w") as f:
    f.write(macro_cpu_rendered)