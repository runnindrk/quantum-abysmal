# Prepare Lattice Structure Data

lattice_template_str = """
#include "../LatticeStructures.hpp"

inline LatticeStructure CodegenLatticeStructure = 
{
    .dimension = 2,
    .numberOfOrbitals = {{ num_orbitals }},
    .latticeSize = {0, 0, 0},
    .numberOfSites = 1,
    .hamiltonianSize = 1,
    .hoppings = {
        {% for hop in hoppings -%}
        { { {{ hop.latticeHop[0] }}, {{ hop.latticeHop[1] }}, {{ hop.latticeHop[2] }} }, { {{ hop.orbitalHop[0] }}, {{ hop.orbitalHop[1] }} }, {{ hop.hoppingStrength }} },
        {% endfor %}
    },
    .numberOfHoppings = {{ hoppings|length }},
    .minEnergy = 0,
    .maxEnergy = 0,
    .energyScaling = 0,
    .energyShift = 0,
    .boundaryType = PERIODIC
};
"""

