# Render CPU Provider Code

def render_cpu_macro(hoppings, num_orbitals):
    lines = []

    lines.append("")
    lines.append("#define CODEGEN_CPU_PROVIDER_KPM_SPARSE(lattice, a, b, x, y, firstMoment, secondMoment)")

    # Temporary variable
    lines.append("")
    lines.append(f"    double temp[{num_orbitals}] = {{}};")

    lines.append("")

    # Hopping terms
    lines.append("    /* Hopping terms (including Hermitian conjugates) */")
    for hop in hoppings:
        lines.append(
            f'    temp[{hop["orbitalHop"][0]}] += lattice.hoppings[{hop["macro_idx"]}].hoppingStrength * b[ARRAY_IDX(x, y, {hop["latticeHop"][0]}, {hop["latticeHop"][1]}, {hop["orbitalHop"][1]})];'
        )

    # Output update
    lines.append("")
    lines.append("    /* Output update */")
    for i in range(num_orbitals):
        lines.append(
            f'    a[ARRAY_IDX(x, y, 0, 0, {i})] = 2 * temp[{i}] - a[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    # First moment
    lines.append("")
    lines.append("    /* First moment */")
    for i in range(num_orbitals):
        lines.append(
            f'    firstMoment += b[ARRAY_IDX(x, y, 0, 0, {i})] * b[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    # Second moment
    lines.append("")
    lines.append("    /* Second moment */")
    for i in range(num_orbitals):
        lines.append(
            f'    secondMoment += a[ARRAY_IDX(x, y, 0, 0, {i})] * b[ARRAY_IDX(x, y, 0, 0, {i})];'
        )

    # Calculate padding
    max_len = max(len(line) for line in lines if line.strip())
    tab_size = 4
    space_count = ((max_len + tab_size) // tab_size) * tab_size
    padded_lines = [(line + " " * (space_count - len(line)) + "\\") for line in lines]

    return "\n".join(padded_lines)

